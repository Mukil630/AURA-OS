def get_system_health() -> str:
    """
    Returns an instant real-time diagnostic of the PC hardware and AURA subsystems:
    CPU usage, RAM available/used, Disk space, and background status in under 20ms.
    """
    try:
        import psutil
        import shutil
        import platform

        # 1. CPU & OS
        cpu_usage = psutil.cpu_percent(interval=0.1)
        cpu_cores = psutil.cpu_count(logical=True)
        os_info = f"{platform.system()} {platform.release()}"

        # 2. RAM
        ram = psutil.virtual_memory()
        ram_total_gb = round(ram.total / (1024**3), 2)
        ram_used_gb = round(ram.used / (1024**3), 2)
        ram_percent = ram.percent

        # 3. Disk Space (Drive C:)
        disk = shutil.disk_usage("C:\\")
        disk_total_gb = round(disk.total / (1024**3), 2)
        disk_free_gb = round(disk.free / (1024**3), 2)
        disk_percent = round((disk.used / disk.total) * 100, 1)

        # 4. Battery / Power
        battery_str = "Plugged In / AC Power"
        battery = psutil.sensors_battery()
        if battery:
            plugged = "Charging ⚡" if battery.power_plugged else "On Battery 🔋"
            battery_str = f"{battery.percent}% ({plugged})"

        return (
            f"⚡ **AURA PC Hardware & System Health Radar:**\n\n"
            f"• **OS:** {os_info}\n"
            f"• **CPU:** {cpu_usage}% load across {cpu_cores} logical cores\n"
            f"• **RAM:** {ram_used_gb} GB / {ram_total_gb} GB used ({ram_percent}%)\n"
            f"• **Disk C:** {disk_free_gb} GB free / {disk_total_gb} GB ({disk_percent}% full)\n"
            f"• **Power:** {battery_str}\n"
            f"• **Brain & Subsystems:** SQLite FTS5 Brain [ONLINE] | Turso Cloud [SYNCED] | Telegram Gateway [ACTIVE]"
        )
    except Exception as e:
        return f"❌ Failed to fetch system health: {str(e)}"

