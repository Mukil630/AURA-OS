def run_command(command: str) -> str:
    """
    Executes a shell or PowerShell command on the system and returns its stdout and stderr.
    Args:
        command: The command line string to execute.
    """
    try:
        proc = subprocess.run(
            ["powershell", "-NoProfile", "-Command", command],
            capture_output=True,
            text=True,
            timeout=45,
            encoding="utf-8",
            errors="replace"
        )
        out = proc.stdout.strip()
        err = proc.stderr.strip()
        
        # Guard against huge outputs (e.g. dumping raw HTML) that blow up token limits
        MAX_OUTPUT_CHARS = 3500
        if len(out) > MAX_OUTPUT_CHARS:
            out = out[:MAX_OUTPUT_CHARS] + f"\n\n[... Truncated {len(out) - MAX_OUTPUT_CHARS} chars to protect token budget ...]"
        if len(err) > MAX_OUTPUT_CHARS:
            err = err[:MAX_OUTPUT_CHARS] + f"\n\n[... Truncated {len(err) - MAX_OUTPUT_CHARS} chars to protect token budget ...]"

        result = []
        if out:
            result.append(f"STDOUT:\n{out}")
        if err:
            result.append(f"STDERR:\n{err}")
        if not result:
            result.append(f"Command executed successfully with return code {proc.returncode} (no output).")
        return "\n".join(result)
    except subprocess.TimeoutExpired:
        return "Error: Command timed out after 45 seconds."
    except Exception as e:
        return f"Error executing command: {str(e)}"


def view_file(path: str, start_line: int = 1, end_line: int = 100) -> str:
    """
    Views the content of a file with line numbers, similar to AGY's view_file.
    Args:
        path: Absolute or relative path to the file.
        start_line: 1-indexed starting line number.
        end_line: 1-indexed ending line number.
    """
    target = Path(path)
    if not target.exists():
        return f"Error: File does not exist at '{path}'"
    if not target.is_file():
        return f"Error: Path '{path}' is a directory, not a file."

    # Binary file guard - strictly block dumping audio/image/binary files into LLM context
    BINARY_EXTS = {".mp3", ".wav", ".ogg", ".png", ".jpg", ".jpeg", ".pdf", ".zip", ".tar", ".gz", ".exe", ".pyc", ".db", ".sqlite"}
    if target.suffix.lower() in BINARY_EXTS:
        return f"Error: '{target.name}' is a binary file ({target.suffix}). view_file only reads text/source code files."

    try:
        with open(target, "r", encoding="utf-8", errors="replace") as f:
            lines = f.readlines()
        
        total_lines = len(lines)
        start = max(1, start_line)
        end = min(total_lines, end_line)
        
        if start > total_lines:
            return f"File has only {total_lines} lines. Requested start line {start} is beyond end of file."
        
        output = [f"File: {target.resolve()} (Lines {start}-{end} of {total_lines})"]
        for idx in range(start - 1, end):
            output.append(f"{idx + 1:4d}: {lines[idx].rstrip()}")
        return "\n".join(output)
    except Exception as e:
        return f"Error reading file '{path}': {str(e)}"


def write_file(path: str, content: str, overwrite: bool = True) -> str:
    """
    Creates or overwrites a file on disk. Automatically creates missing parent directories.
    Args:
        path: Path to target file.
        content: Text content to write into the file.
        overwrite: Set to True to overwrite existing file.
    """
    target = Path(path)
    if target.exists() and not overwrite:
        return f"Error: File '{path}' already exists and overwrite is set to False."

    try:
        target.parent.mkdir(parents=True, exist_ok=True)
        with open(target, "w", encoding="utf-8") as f:
            f.write(content)
        return f"Successfully wrote {len(content)} characters to '{target.resolve()}'."
    except Exception as e:
        return f"Error writing file '{path}': {str(e)}"


